//! `wcwidth` / `wcswidth`：字符在**终端上的显示列数**（POSIX `<wchar.h>`）。
//!
//! ## 为什么需要（本轮缺陷驱动，不是"看起来该有"）
//!
//! `tools/3psrc/cowsay/cowsay.c` 为了按显示列折行，自己写了一份 `disp_width`，并在注释里
//! **如实声明**「这不是完整 wcwidth（没有 Unicode 宽度表），只覆盖常见区间」。
//! 一份私有近似表的后果是：任何需要列宽的第三方程序都得再抄一份，且各抄各的、迟早分叉。
//! 正确的落点是 libc 提供 `wcwidth`（POSIX 本就要求它），调用方只调用它。
//!
//! ## 表与诚实边界（S09）
//!
//! 两张区间表（**零宽**：组合符号与格式控制；**双宽**：东亚宽/全角）取自 Markus Kuhn 的
//! 公开实现 `wcwidth.c`（public domain），对应 **Unicode 5.0** 时代的 EastAsianWidth 与
//! 组合类；在此之上**额外**收录 Unicode 6.0 起定为宽字符的绘文字区间（见 `EMOJI_WIDE`）。
//!
//! **仍然诚实的边界**：这是**区间近似**，不是从最新 `UnicodeData.txt` 生成的精确表——
//! 表里没有的字符一律按 1 列计。新版 Unicode 若改了某区间的宽度，本表**不会自动跟随**；
//! 跟随的办法是用新版 `UnicodeData.txt` 的 EastAsianWidth/General_Category 重新生成一次。
//! **本模块绝不自称"完整 wcwidth"。**

