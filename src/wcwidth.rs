/// **双宽**：东亚宽（W）与全角（F）。
const WIDE: &[Interval] = &[
    (0x1100, 0x115F), (0x2329, 0x232A), (0x2E80, 0x303E), (0x3041, 0x33FF),
    (0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xA000, 0xA4CF), (0xAC00, 0xD7A3),
    (0xF900, 0xFAFF), (0xFE10, 0xFE19), (0xFE30, 0xFE6F), (0xFF00, 0xFF60),
    (0xFFE0, 0xFFE6), (0x20000, 0x2FFFD), (0x30000, 0x3FFFD),
];

/// **双宽（Unicode 6.0 起）**：绘文字与补充符号中定为宽字符的区间。
///
/// 为什么不把整个 `U+2600..U+27BF` 也算宽：那一大段在 EastAsianWidth 里是
/// **Ambiguous/Neutral**（西文终端按 1 列），按 2 列算会让西文终端折行提前——
/// **宁可少算也不多算**（S09：不夸大能力，也不制造错位）。
const EMOJI_WIDE: &[Interval] = &[
    (0x1F300, 0x1F5FF), (0x1F600, 0x1F64F), (0x1F680, 0x1F6FF),
    (0x1F900, 0x1F9FF), (0x1FA70, 0x1FAFF),
];

/// 区间表二分查找（表为空或越界立即 false）。
fn bisearch(ucs: u32, table: &[Interval]) -> bool {
    if table.is_empty() {
        return false;
    }
    if ucs < table[0].0 || ucs > table[table.len() - 1].1 {
        return false;
    }
    let mut min: i32 = 0;
    let mut max: i32 = table.len() as i32 - 1;
    while min <= max {
        let mid = ((min + max) / 2) as usize;
        if ucs > table[mid].1 {
            min = mid as i32 + 1;
        } else if ucs < table[mid].0 {
            max = mid as i32 - 1;
        } else {
            return true;
        }
    }
    false
}

/// `wcwidth(wc)`：`wc` 在终端上占的列数。
///
/// 返回值（POSIX）：`0` = 零宽（组合符号/格式控制）；`2` = 宽/全角；`1` = 其余可打印；
/// `-1` = **不可打印**（控制字符，含 `DEL` 与 C1）。
#[unsafe(no_mangle)]
pub unsafe extern "C" fn wcwidth(wc: wchar_t) -> c_int {
    let ucs = wc as u32;
    if ucs == 0 {
        return 0;
    }
    if ucs < 32 || (0x7f..0xa0).contains(&ucs) {
        return -1;
    }
    if bisearch(ucs, COMBINING) {
        return 0;
    }
    if bisearch(ucs, WIDE) || bisearch(ucs, EMOJI_WIDE) {
        return 2;
    }
    1
}

/// `wcswidth(s, n)`：至多 `n` 个宽字符的显示列数之和。
///
/// 任一字符不可打印即返回 `-1`（POSIX 语义）；遇到 `L'\0'` 提前结束。
#[unsafe(no_mangle)]
pub unsafe extern "C" fn wcswidth(s: *const wchar_t, n: size_t) -> c_int {
    if s.is_null() {
        return -1;
    }
    let mut total: c_int = 0;
    let mut i = 0usize;
    while i < n {
        let wc = unsafe { *s.add(i) };
        if wc == 0 {
            break;
        }
        let w = unsafe { wcwidth(wc) };
        if w < 0 {
            return -1;
        }
        total += w;
        i += 1;
    }
    total
}